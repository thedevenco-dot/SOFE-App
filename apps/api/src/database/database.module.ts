import { Global, Module } from '@nestjs/common';
import { MongooseModule } from '@nestjs/mongoose';
import { ConfigService } from '@nestjs/config';
import {
  User,
  UserSchema,
  AdminUser,
  AdminUserSchema,
  AuditLog,
  AuditLogSchema,
  AppConfig,
  AppConfigSchema,
  CourseCategory,
  CourseCategorySchema,
  Instructor,
  InstructorSchema,
  Topic,
  TopicSchema,
  Author,
  AuthorSchema,
  Course,
  CourseSchema,
  Lesson,
  LessonSchema,
  Article,
  ArticleSchema,
  Book,
  BookSchema,
  Video,
  VideoSchema,
  Quote,
  QuoteSchema,
  Word,
  WordSchema,
  WebhookEvent,
  WebhookEventSchema,
  Enrollment,
  EnrollmentSchema,
  ContentVersion,
  ContentVersionSchema,
  Bookmark,
  BookmarkSchema,
  TopicFollow,
  TopicFollowSchema,
  Achievement,
  AchievementSchema,
  UserAchievement,
  UserAchievementSchema,
  Project,
  ProjectSchema,
} from './schemas';

@Global()
@Module({
  imports: [
    MongooseModule.forRootAsync({
      inject: [ConfigService],
      useFactory: (config: ConfigService) => ({
        uri: config.get<string>('MONGODB_URI', 'mongodb://127.0.0.1:27017/sofe_dev'),
        dbName: config.get<string>('MONGODB_DB_NAME', 'sofe_dev'),
        maxPoolSize: 20,
        retryWrites: true,
      }),
    }),
    MongooseModule.forFeature([
      { name: User.name, schema: UserSchema },
      { name: AdminUser.name, schema: AdminUserSchema },
      { name: AuditLog.name, schema: AuditLogSchema },
      { name: AppConfig.name, schema: AppConfigSchema },
      { name: CourseCategory.name, schema: CourseCategorySchema },
      { name: Instructor.name, schema: InstructorSchema },
      { name: Topic.name, schema: TopicSchema },
      { name: Author.name, schema: AuthorSchema },
      { name: Course.name, schema: CourseSchema },
      { name: Lesson.name, schema: LessonSchema },
      { name: Article.name, schema: ArticleSchema },
      { name: Book.name, schema: BookSchema },
      { name: Video.name, schema: VideoSchema },
      { name: Quote.name, schema: QuoteSchema },
      { name: Word.name, schema: WordSchema },
      { name: WebhookEvent.name, schema: WebhookEventSchema },
      { name: Enrollment.name, schema: EnrollmentSchema },
      { name: ContentVersion.name, schema: ContentVersionSchema },
      { name: Bookmark.name, schema: BookmarkSchema },
      { name: TopicFollow.name, schema: TopicFollowSchema },
      { name: Achievement.name, schema: AchievementSchema },
      { name: UserAchievement.name, schema: UserAchievementSchema },
      { name: Project.name, schema: ProjectSchema },
    ]),
  ],
  exports: [MongooseModule],
})
export class DatabaseModule {}
